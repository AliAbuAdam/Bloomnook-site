/**
 * ЧПУ-адреса (slug) для SEO-страниц товаров и категорий.
 *
 * Slug вычисляется детерминированно из данных товара — и при статической
 * сборке (generateStaticParams), и на клиенте (ссылки в карточках) получается
 * один и тот же адрес без хранения slug в базе.
 */

/** Транслитерация кириллицы в латиницу (ГОСТ-подобная, для URL). */
const RU_TO_LAT: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh",
  з: "z", и: "i", й: "y", к: "k", л: "l", м: "m", н: "n", о: "o",
  п: "p", р: "r", с: "s", т: "t", у: "u", ф: "f", х: "h", ц: "ts",
  ч: "ch", ш: "sh", щ: "sch", ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
};

/** «Лилия «Йеллоуин» 20/22» → «liliya-yellouin-20-22». */
export function slugify(text: string): string {
  return text
    .toLowerCase()
    .split("")
    .map((ch) => RU_TO_LAT[ch] ?? ch)
    .join("")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/**
 * Slug страницы товара — из полного названия (оно содержит категорию, сорт и
 * разбор, поэтому практически всегда уникально). При совпадении имён двух
 * товаров оба адреса укажут на первый по порядку каталога — следите за
 * уникальностью названий в админке.
 */
export function productSlug(p: { name: string }): string {
  return slugify(p.name) || "tovar";
}

/** Slug страницы категории: «Тюльпан» → «tyulpan». */
export function categorySlug(cat: string): string {
  return slugify(cat) || "vse";
}

/**
 * Заголовки категорий во множественном числе — для h1/title страниц категорий.
 * Для категорий, добавленных в админке позже, используется имя как есть.
 */
const CATEGORY_PLURAL: Record<string, string> = {
  "Тюльпан": "Тюльпаны",
  "Лилия": "Лилии",
  "Нарцисс": "Нарциссы",
  "Гиацинт": "Гиацинты",
  "Крокус": "Крокусы",
  "Ирис": "Ирисы",
  "Гименокаллис": "Гименокаллисы",
  "Эукомис": "Эукомисы",
};

export function categoryPlural(cat: string): string {
  return CATEGORY_PLURAL[cat] ?? cat;
}

/**
 * Родительный падеж множественного числа — для фраз вида «купить луковицы
 * тюльпанов». Для неизвестных категорий строим фразу без склонения.
 */
const CATEGORY_GENITIVE: Record<string, string> = {
  "Тюльпан": "тюльпанов",
  "Лилия": "лилий",
  "Нарцисс": "нарциссов",
  "Гиацинт": "гиацинтов",
  "Крокус": "крокусов",
  "Ирис": "ирисов",
  "Гименокаллис": "гименокаллисов",
  "Эукомис": "эукомисов",
};

export function categoryGenitive(cat: string): string | null {
  return CATEGORY_GENITIVE[cat] ?? null;
}
